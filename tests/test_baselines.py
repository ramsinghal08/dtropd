def test_calibrate_attenuation_procedure():
    rng = np.random.default_rng(0)
    samples = rng.gamma(shape=2.0, scale=0.01, size=5000)
    result = calibrate_attenuation(samples, quantile=0.5, tail_quantile=0.95, target_w=0.5)

    assert result["delta_base"] == pytest.approx(float(np.quantile(samples, 0.5)))
    # An edge at the tail quantile must be attenuated to exactly target_w.
    from dtropd.algorithms import trust_weight

    w = float(
        trust_weight(
            torch.tensor(float(np.quantile(samples, 0.95)), dtype=torch.float64),
            result["delta_base"],
            result["gamma_attenuation"],
        )
    )
    assert w == pytest.approx(0.5, rel=1e-6)
    # ...and an identical neighbour is still fully trusted (I7).
    assert float(
        trust_weight(
            torch.tensor(0.0, dtype=torch.float64),
            result["delta_base"],
            result["gamma_attenuation"],
        )
    ) == pytest.approx(1.0, abs=1e-12)


def test_calibrate_attenuation_rejects_empty_input():
    with pytest.raises(ValueError):
        calibrate_attenuation([])


def test_warmup_calibration_runs_inside_training():
    cfg = baseline_config("dtropd", n_agents=4)
    cfg.distill.calibration = "warmup"
    cfg.distill.warmup_epochs = 2
    cfg.distill.beta_max = 0.5
    cfg.validate(emit=False)

    algo, history = run_epochs(cfg, seed=7, epochs=4)
    assert algo._calibrated
    assert algo.delta_base != cfg.distill.delta_base
    calibrated_epochs = [h for h in history if "calibrated_at_epoch" in h]
    assert len(calibrated_epochs) == 1
    assert calibrated_epochs[0]["calibrated_at_epoch"] == 1  # end of the window
    # beta is exactly 0 for the whole calibration window, so the measurement
    # cannot have been influenced by the gate it calibrates (SPEC Sec. 10 / D1).
    assert all(h["beta"] == 0.0 for h in history[:2])
    # ...and the ramp starts afterwards, so I8 still gets a real warmup.
    assert history[2]["beta"] == 0.0
    assert history[-1]["beta"] > 0.0


def test_calibration_default_is_off():
    cfg = baseline_config("dtropd")
    assert cfg.distill.calibration == "none"
    algo, _ = run_epochs(cfg, seed=0, epochs=2)
    assert algo.delta_base == cfg.distill.delta_base
    assert algo.gamma_attenuation == cfg.distill.gamma_attenuation


