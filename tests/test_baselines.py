def test_naive_distill_and_dtropd_diverge_when_the_gate_bites():
    """With a tight radius the two must not coincide -- else D4 buys nothing."""
    naive, _ = run_epochs(
        baseline_config("naive_distill", n_agents=4), seed=8, epochs=3
    )
    cfg = baseline_config("dtropd", n_agents=4)
    cfg.distill.delta_base = 1e-4  # radius far below any observed D_ij
    cfg.distill.gamma_attenuation = 50.0
    cfg.distill.beta_max = 0.5
    cfg.distill.warmup_epochs = 0
    cfg.validate(emit=False)
    gated, _ = run_epochs(cfg, seed=8, epochs=3)
    assert any(
        not torch.equal(a.detach(), b.detach())
        for x, y in zip(naive.agents, gated.agents)
        for a, b in zip(x.parameters(), y.parameters())
    )


