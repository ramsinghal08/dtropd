REFERENCE = Path(__file__).resolve().parent / "data" / "ippo_phase2_reference.json"

ALL_ALGOS = ("ippo", "mappo", "happo", "naive_distill", "dtropd")

#: Tolerances for the cross-machine golden-curve comparison live in
#: ``dtropd.golden``, which explains at length why exact equality, then pointwise
#: relative error, then fraction-of-dynamic-range were each the wrong assertion.
#:
#: The absolute deviations CI actually produced at epoch 0, which the tolerance
#: must accept. Three metrics whose magnitudes span three orders of magnitude,
#: and whose round-off is the same ~1e-8: the noise floor is absolute.
CI_OBSERVED_FIRST_EPOCH_DEVIATION = {
    "episode_return_mean": 4.942e-8,
    "explained_variance": 6.205e-9,
    "update_kl": 8.925e-9,
}


def baseline_config(algo: str, n_agents: int = 4) -> Config:
    """One config, one set of hyperparameters, shared by every algorithm."""
    cfg = Config()
    cfg.env.n_agents = n_agents
    cfg.env.n_targets = 1
    cfg.env.capture_group_size = 2
    cfg.env.max_cycles = 8
    cfg.train.algo = algo
    cfg.train.num_envs = 2
    cfg.train.total_epochs = 3
    cfg.train.device = "cpu"
    cfg.ppo.inner_epochs = 2
    cfg.ppo.num_minibatches = 2
    cfg.network.hidden_sizes = [16, 16]
    cfg.distill.enabled = algo in ("dtropd", "naive_distill")
    cfg.distill.beta_max = 0.05
    cfg.validate(emit=False)
    return cfg


def run_epochs(cfg: Config, seed: int = 0, epochs: int | None = None):
    algo = build_algorithm(cfg, seed=seed, device="cpu")
    vec = SyncVectorEnv(cfg.env, cfg.train.num_envs, seed=derive_seed(seed, "env"))
    history = []
    for epoch in range(epochs if epochs is not None else cfg.train.total_epochs):
        algo.epoch = epoch
        algo.on_epoch_start()
        rollout = algo.collect_rollout(vec)
        metrics = algo.update()
        history.append({**rollout, **{k: v for k, v in metrics.items() if k != "per_agent"}})
    return algo, history


