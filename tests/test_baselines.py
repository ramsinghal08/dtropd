def test_naive_distill_weights_every_neighbour_equally():
    cfg = baseline_config("naive_distill", n_agents=4)
    algo = build_algorithm(cfg, seed=0, device="cpu")
    vec = SyncVectorEnv(cfg.env, cfg.train.num_envs, seed=0)
    algo.on_epoch_start()
    algo.collect_rollout(vec)
    algo._beta = 1.0
    data = algo.buffer.agent_tensors(0)
    state = algo._prepare_epoch(0, data)
    algo._social[0] = state
    # No weight field exists at all -- w = 1 is structural, not a stored value.
    assert not hasattr(state, "weight")
    assert not hasattr(state, "divergence")

    idx = torch.arange(data["obs"].shape[0])
    out = algo.agents[0].actor.evaluate_latent(data["obs"], data["latent"])
    terms = algo._social_terms(0, out, idx)
    raw = algo._per_neighbor_kl(state, out, idx)
    assert torch.equal(terms, raw), "something attenuated a NaiveDistill term"


