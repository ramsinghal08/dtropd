def test_radius_reference_default_is_fixed():
    cfg = baseline_config("dtropd")
    assert cfg.distill.radius_reference == "fixed"
    algo, history = run_epochs(cfg, seed=0, epochs=3)
    assert all(h["delta_base_effective"] == cfg.distill.delta_base for h in history)


def test_running_quantile_radius_tracks_observed_divergence():
    cfg = baseline_config("dtropd", n_agents=4)
    cfg.distill.radius_reference = "running_quantile"
    cfg.validate(emit=False, strict=True)
    algo, history = run_epochs(cfg, seed=0, epochs=4)
    # First epoch has no history yet, later epochs track the observed median.
    assert history[0]["delta_base_effective"] == cfg.distill.delta_base
    later = [h["delta_base_effective"] for h in history[1:]]
    assert any(v != cfg.distill.delta_base for v in later), (
        "running_quantile never moved the radius reference"
    )


def test_running_quantile_is_warned_about():
    cfg = baseline_config("dtropd")
    cfg.distill.radius_reference = "running_quantile"
    warnings_out = cfg.validate(emit=False)
    assert any("scale-invariance" in w for w in warnings_out)


def test_divergence_drift_is_logged_in_both_radius_arms():
    """D5: the confound must be measured whichever arm is used."""
    for reference in ("fixed", "running_quantile"):
        cfg = baseline_config("dtropd", n_agents=4)
        cfg.distill.radius_reference = reference
        cfg.validate(emit=False)
        _, history = run_epochs(cfg, seed=0, epochs=3)
        for h in history:
            for key in (
                "social_divergence_p5",
                "social_divergence_p50",
                "social_divergence_p95",
                "social_divergence_drift",
            ):
                assert key in h, f"{reference}: missing {key}"
        assert history[0]["social_divergence_drift"] == pytest.approx(1.0)
