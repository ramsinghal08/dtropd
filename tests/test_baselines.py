@pytest.mark.parametrize("algo", ALL_ALGOS)
def test_every_algorithm_trains_end_to_end(algo, tmp_path):
    cfg = baseline_config(algo)
    cfg.train.log_dir = str(tmp_path)
    cfg.train.eval_interval = 0
    cfg.train.eval_episodes = 2
    result = train(cfg, seed=0, out_dir=tmp_path / algo, progress=False)

    records = read_metrics(result.run_dir / "metrics.jsonl")
    assert len(records) == cfg.train.total_epochs
    for rec in records:
        assert np.isfinite(rec["episode_return_mean"])
        assert np.isfinite(rec["value_loss"])
    meta = json.loads((result.run_dir / "metadata.json").read_text())
    assert meta["reward_spec_version"] == "v1"  # SPEC Sec. 10 / D3


@pytest.mark.parametrize("algo", ALL_ALGOS)
def test_algorithms_share_hyperparameters_and_seeds(algo):
    """Identical seeds and hyperparameters produce identical initial policies."""
    a, _ = run_epochs(baseline_config(algo), seed=3, epochs=0)
    b, _ = run_epochs(baseline_config("ippo"), seed=3, epochs=0)
    for pa, pb in zip(a.agents[0].actor.parameters(), b.agents[0].actor.parameters()):
        assert torch.equal(pa, pb), (
            "algorithms with the same seed start from different actors -- the "
            "comparison would be confounded before the first update"
        )


@pytest.mark.parametrize("algo", ALL_ALGOS)
def test_algorithms_are_deterministic_under_a_seed(algo):
    a, ha = run_epochs(baseline_config(algo), seed=5)
    b, hb = run_epochs(baseline_config(algo), seed=5)
    for pa, pb in zip(a.agents[1].parameters(), b.agents[1].parameters()):
        assert torch.equal(pa, pb)
    assert [h["episode_return_mean"] for h in ha] == [h["episode_return_mean"] for h in hb]


