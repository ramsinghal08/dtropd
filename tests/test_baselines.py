def test_happo_resamples_a_random_order_each_epoch():
    cfg = baseline_config("happo", n_agents=6)
    algo, history = run_epochs(cfg, seed=1, epochs=6)
    assert isinstance(algo, HAPPO)
    orders = [tuple(h["happo_order"]) for h in history]
    for order in orders:
        assert sorted(order) == list(range(6)), "not a permutation of the agents"
    assert len(set(orders)) > 1, "the update order never changed across epochs"


def test_happo_order_is_seeded_and_reproducible():
    a, ha = run_epochs(baseline_config("happo", n_agents=5), seed=2, epochs=4)
    b, hb = run_epochs(baseline_config("happo", n_agents=5), seed=2, epochs=4)
    assert [h["happo_order"] for h in ha] == [h["happo_order"] for h in hb]
    c, hc = run_epochs(baseline_config("happo", n_agents=5), seed=99, epochs=4)
    assert [h["happo_order"] for h in ha] != [h["happo_order"] for h in hc]


def test_happo_sequential_factor_is_live():
    """The correction factor starts at 1 and moves as predecessors update."""
    cfg = baseline_config("happo", n_agents=4)
    algo, history = run_epochs(cfg, seed=4, epochs=3)
    assert algo._factor is not None
    assert algo._factor.shape == (algo.buffer.batch_size,)
    assert not torch.allclose(algo._factor, torch.ones_like(algo._factor)), (
        "the HAPPO factor never moved: sequential updates have no correction"
    )
    assert all(np.isfinite(h["happo_factor_mean"]) for h in history)


def test_happo_differs_from_ippo():
    ippo, _ = run_epochs(baseline_config("ippo", n_agents=4), seed=6)
    happo, _ = run_epochs(baseline_config("happo", n_agents=4), seed=6)
    assert any(
        not torch.equal(a.detach(), b.detach())
        for x, y in zip(ippo.agents, happo.agents)
        for a, b in zip(x.parameters(), y.parameters())
    )


