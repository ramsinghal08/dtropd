def test_mappo_critic_sees_the_concatenated_observation():
    cfg = baseline_config("mappo", n_agents=4)
    algo = build_algorithm(cfg, seed=0, device="cpu")
    assert isinstance(algo, MAPPO)
    assert algo.critic_obs_dim == cfg.env.obs_dim * cfg.env.n_agents
    first_linear = next(m for m in algo.agents[0].critic.net if isinstance(m, torch.nn.Linear))
    assert first_linear.weight.shape[1] == algo.critic_obs_dim

    vec = SyncVectorEnv(cfg.env, cfg.train.num_envs, seed=0)
    algo.on_epoch_start()
    algo.collect_rollout(vec)
    data = algo.buffer.agent_tensors(0)
    assert data["critic_obs"].shape[1] == algo.critic_obs_dim
    # Every agent's critic input at a transition is the same joint vector...
    other = algo.buffer.agent_tensors(1)
    assert torch.equal(data["critic_obs"], other["critic_obs"])
    # ...and it really is the concatenation of the per-agent observations.
    joint = torch.cat([algo.buffer.agent_tensors(i)["obs"] for i in range(4)], dim=1)
    assert torch.equal(data["critic_obs"], joint)


def test_mappo_actors_stay_decentralised():
    cfg = baseline_config("mappo", n_agents=3)
    algo = build_algorithm(cfg, seed=0, device="cpu")
    for ac in algo.agents:
        first_linear = next(m for m in ac.actor.net if isinstance(m, torch.nn.Linear))
        assert first_linear.weight.shape[1] == cfg.env.obs_dim


def test_only_mappo_widens_the_critic():
    """SPEC Sec. 2: D-TrOPD has no central critic -- structurally, not by config."""
    for algo_name in ("ippo", "happo", "naive_distill", "dtropd"):
        cfg = baseline_config(algo_name)
        algo = build_algorithm(cfg, seed=0, device="cpu")
        assert algo.critic_obs_dim == cfg.env.obs_dim, algo_name


