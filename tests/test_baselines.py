def reference_config() -> Config:
    """The exact configuration the stored Phase 2 golden curve was produced with."""
    spec = json.loads(REFERENCE.read_text())["config_summary"]
    cfg = Config()
    cfg.env.n_agents = spec["n_agents"]
    cfg.env.n_targets = spec["n_targets"]
    cfg.env.capture_group_size = 3
    cfg.env.max_cycles = spec["max_cycles"]
    cfg.env.local_ratio = 0.5
    cfg.network.hidden_sizes = list(spec["hidden"])
    cfg.train.algo = "ippo"
    cfg.train.num_envs = spec["num_envs"]
    cfg.train.total_epochs = spec["epochs"]
    cfg.ppo.lr = spec["lr"]
    cfg.validate(emit=False)
    return cfg


def compare_to_reference_curve(
    actual: Sequence[float],
    expected: Sequence[float],
    key: str,
    granularity: float | None = None,
) -> golden.CurveVerdict:
    """Assert a curve still matches the golden reference, at the right precision.

    The rule itself lives in :mod:`dtropd.golden`, shared with
    ``experiments/phase4_acceptance.py`` -- when it was written out twice, one
    copy got fixed and the other did not.
    """
    verdict = golden.compare_curve(key, actual, expected, granularity=granularity)
    assert verdict.ok, verdict.reason
    return verdict


def test_ippo_curves_match_the_phase2_reference():
    """IPPO is unchanged by the Phase 3/4/5 refactors.

    Compared against a curve generated by running IPPO on the **Phase 2 commit**
    (011de8f) in a worktree -- pre-refactor code, not this tree.
    """
    reference = json.loads(REFERENCE.read_text())
    _, history = run_epochs(reference_config(), seed=reference["config_summary"]["seed"])
    for key, expected in reference["curve"].items():
        compare_to_reference_curve([h[key] for h in history], expected, key)


def test_reference_comparison_rejects_a_real_change_and_tolerates_round_off():
    """The tolerance itself is tested, so it cannot be quietly widened later."""
    expected = json.loads(REFERENCE.read_text())["curve"]["episode_return_mean"]
    e = np.asarray(expected, dtype=np.float64)

    # Cross-machine round-off, at the magnitude CI actually exhibited: a 2e-9
    # relative perturbation at epoch 0 growing to 5e-7 by the last epoch.
    growth = np.geomspace(2e-9, 5e-7, e.size)
    compare_to_reference_curve(e * (1.0 + growth), expected, "episode_return_mean")

    # A real change in the update math: 0.1% from the very first epoch.
    with pytest.raises(AssertionError, match="at the FIRST epoch"):
        compare_to_reference_curve(e * 1.001, expected, "episode_return_mean")

    # A change that starts clean but diverges later must also fail.
    late = np.ones_like(e)
    late[e.size // 2 :] = 1.01
    with pytest.raises(AssertionError, match="diverged from the Phase 2 reference"):
        compare_to_reference_curve(e * late, expected, "episode_return_mean")

    # A different number of epochs is a mismatch, not a tolerance question.
    with pytest.raises(AssertionError, match="epochs"):
        compare_to_reference_curve(e[:-1], expected, "episode_return_mean")


@pytest.mark.parametrize("key,deviation", sorted(CI_OBSERVED_FIRST_EPOCH_DEVIATION.items()))
def test_tolerance_accepts_the_round_off_ci_actually_produced(key, deviation):
    """Regression for three red builds, using the numbers from each of them.

    ``explained_variance`` starts at -0.0099 (an untrained critic explains
    nothing) and rises to 0.58, so pointwise relative error inflated its 6.2e-9
    round-off into 6.3e-7. ``update_kl`` is an O(0.01) difference of O(1)
    log-probs with a dynamic range of 0.0062, so fraction-of-range inflated its
    8.9e-9 into 1.4e-6. Both are the same absolute round-off as the return
    curve's 4.9e-8, on metrics 3000x smaller.
    """
    expected = json.loads(REFERENCE.read_text())["curve"][key]
    e = np.asarray(expected, dtype=np.float64)

    verdict = compare_to_reference_curve(e + deviation, expected, key)
    assert verdict.first_epoch_deviation <= verdict.tolerances["first_epoch"] / 10, (
        f"{key}: the epoch-0 tolerance should clear observed round-off by a wide "
        "margin, not scrape past it"
    )

    # ...and the amplified version of it by the end of the run. CI showed roughly
    # two orders of magnitude of chaotic growth over twelve epochs.
    amplified = e + np.geomspace(deviation, deviation * 300.0, e.size)
    compare_to_reference_curve(amplified, expected, key)


@pytest.mark.parametrize("key", sorted(json.loads(REFERENCE.read_text())["curve"]))
def test_first_epoch_tolerance_still_detects_a_real_change(key):
    """Detection power, checked for every metric rather than argued in prose.

    The tolerance has been widened twice. What must survive is the epoch-0
    assertion's ability to catch a change in the update math -- so for *each*
    reference metric, the smallest change worth calling real must still fail.

    For a continuous metric that is a 1%-of-magnitude shift. A count cannot take
    such a value at all: 1% of ``inner_epochs_used`` is 0.24 of its 1/6 step,
    below the metric's own resolution. The smallest real change it can express is
    two flipped decisions, one more than round-off explains.
    """
    expected = json.loads(REFERENCE.read_text())["curve"][key]
    e = np.asarray(expected, dtype=np.float64)
    step = golden.infer_step(expected)
    shift = 2.0 * step if step else 0.01 * float(np.max(np.abs(e)))

    with pytest.raises(AssertionError):
        compare_to_reference_curve(e + shift, expected, key)


@pytest.mark.parametrize("key", golden.STEP_VALUED_KEYS)
def test_discrete_metrics_are_recognised_as_counts(key):
    """The keys known to be counts must still be inferred as counts.

    ``inner_epochs_used`` is how many inner epochs ran before the KL early-stop
    tripped (averaged over 6 agents, so steps of 1/6) and ``clip_fraction`` is
    the fraction of samples the PPO ratio clipped (steps of 1/4800). Both respond
    to round-off in whole steps, not as a smooth drift, so both need comparing in
    their own units -- and neither should depend on someone remembering to say
    so.
    """
    expected = json.loads(REFERENCE.read_text())["curve"][key]
    step = golden.infer_step(expected)
    assert step is not None, (
        f"{key} is a count but was classified as continuous; a single flipped "
        "threshold decision would then read as a behaviour change"
    )
    assert golden.compare_curve(key, expected, expected).kind == "step"


def test_step_valued_metrics_are_compared_in_their_own_units():
    """One flipped decision is round-off; a bulk shift is a behaviour change.

    A borderline KL early-stop comparison decided differently on another machine
    moves ``inner_epochs_used`` by exactly ``1/n_agents`` -- for the reference
    config that is 100% of this curve's range, so no continuous tolerance can
    both accept it and mean anything.
    """
    expected = json.loads(REFERENCE.read_text())["curve"]["inner_epochs_used"]
    e = np.asarray(expected, dtype=np.float64)
    step = golden.infer_step(expected)

    # One agent early-stopping one inner epoch differently: attributable to round-off.
    one_flip = e.copy()
    one_flip[3] += step
    compare_to_reference_curve(one_flip, expected, "inner_epochs_used")

    # Two agents at the same epoch is beyond what a single flipped comparison explains.
    two_flips = e.copy()
    two_flips[3] -= 2 * step
    with pytest.raises(AssertionError, match="diverged from the Phase 2 reference"):
        compare_to_reference_curve(two_flips, expected, "inner_epochs_used")

    # The early-stop schedule collapsing is a behaviour change, not round-off.
    with pytest.raises(AssertionError, match="flipped decisions"):
        compare_to_reference_curve(e - 1.0, expected, "inner_epochs_used")


def test_step_inference_does_not_mistake_continuous_curves_for_counts():
    """The inference must not fire on smooth metrics, or it would mask real drift.

    A continuous curve reported as a count would be compared in steps rather than
    against the epoch-0 tolerance, which is where the actual detection power is.
    """
    reference = json.loads(REFERENCE.read_text())["curve"]
    for key in ("episode_return_mean", "explained_variance", "value_loss", "entropy"):
        assert golden.infer_step(reference[key]) is None, f"{key} is not a count"

    rng = np.random.default_rng(0)
    for magnitude in (1e-3, 1.0, 30.0):
        for _ in range(50):
            assert golden.infer_step(rng.normal(size=12) * magnitude) is None


