def test_naive_distill_has_no_radius_or_attenuation_attributes():
    """D4: the baseline must not be reachable from the method by a config value."""
    cfg = baseline_config("naive_distill")
    algo = build_algorithm(cfg, seed=0, device="cpu")
    assert isinstance(algo, NaiveDistill)
    assert not isinstance(algo, DTrOPD)

    banned = (
        "delta_base",
        "gamma_attenuation",
        "prev_snapshots",
        "trust_radius",
        "trust_weight",
        "_nonstationarity",
        "_trust_states",
        "_effective_delta_base",
        "_warn_if_gate_is_inert",
        "_maybe_calibrate",
        "calibrate_from_samples",
        "INERT_GATE_THRESHOLD",
    )
    present = [name for name in banned if hasattr(algo, name)]
    assert not present, f"NaiveDistill exposes radius/attenuation machinery: {present}"
    assert algo.reports_trust_gate is False


def test_naive_distill_weights_every_neighbour_equally():
    cfg = baseline_config("naive_distill", n_agents=4)
    algo = build_algorithm(cfg, seed=0, device="cpu")
    vec = SyncVectorEnv(cfg.env, cfg.train.num_envs, seed=0)
    algo.on_epoch_start()
    algo.collect_rollout(vec)
    algo._beta = 1.0
    data = algo.buffer.agent_tensors(0)
    state = algo._prepare_epoch(0, data)
    algo._social[0] = state
    # No weight field exists at all -- w = 1 is structural, not a stored value.
    assert not hasattr(state, "weight")
    assert not hasattr(state, "divergence")

    idx = torch.arange(data["obs"].shape[0])
    out = algo.agents[0].actor.evaluate_latent(data["obs"], data["latent"])
    terms = algo._social_terms(0, out, idx)
    raw = algo._per_neighbor_kl(state, out, idx)
    assert torch.equal(terms, raw), "something attenuated a NaiveDistill term"


def test_naive_distill_reports_itself_in_the_metrics():
    _, history = run_epochs(baseline_config("naive_distill"), seed=0, epochs=2)
    assert history[-1]["trust_gate"] == "none"
